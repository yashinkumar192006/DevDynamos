"""End-to-end demo: submit → handle a BLOCK → use an approved result.

Designed for the seeded demo customer ``natalie.brooks`` (see
``backend/app/seed.py`` for the demo passwords and ``examples/README.md``
for how to run this). Synthetic seed data only — no real customer data is
involved.

What it shows:

1. A host agent asks for **another customer's** private data → the gateway
   returns ``BLOCK``; the agent handles the refusal and gets **no data**
   (and no model is ever invoked).
2. The same agent asks for **its own order** → ``ALLOW``; the agent uses the
   approved result, including a summary generated by the gateway's mock
   LLM provider (``include_llm_response=True``).

Prerequisite: gateway running against the migrated + seeded demo database.

    python examples/demo_end_to_end.py
"""

from __future__ import annotations

import sys

import _bootstrap


def main() -> None:
    client = _bootstrap.build_client()

    # ── 1. A request that must be blocked ───────────────────────────
    # Natalie tries to read *another* customer's contact details. The
    # gateway evaluates policy server-side and denies everything.
    print("=" * 72)
    print("Probe 1: customer reads another customer's private data (expect BLOCK)")
    blocked = client.secure_request(
        resource="customer_records",
        data_fields=["contact_email", "billing_address"],
        purpose="order_status",
        target_entity="CUS002",  # not Natalie's record
        session_id="demo-end-to-end-1",
        include_llm_response=True,  # ignored: blocked requests never reach a model
    )
    _bootstrap.print_result(blocked)

    if not blocked.blocked:
        print("Unexpected: expected a BLOCK for another customer's data.")
        raise SystemExit(1)

    # A host agent handles the decision without exceptions:
    _respond_to_user(
        blocked, "I'm sorry, I can't access that customer's information."
    )
    print("  note:      no protected data retrieved, model never invoked "
          f"(llm_response={blocked.llm_response!r})")

    # ── 2. A request that is approved ───────────────────────────────
    # Natalie reads her **own** order status. Self-service access is
    # authorized, and only the requested fields are returned.
    print("=" * 72)
    print("Probe 2: customer reads their own order (expect ALLOW)")
    approved = client.secure_request(
        resource="order_records",
        data_fields=["order_id", "status", "total_amount"],
        purpose="order_status",
        target_entity="ORD0001",  # Natalie's own order
        session_id="demo-end-to-end-1",
        include_llm_response=True,  # answered by the mock LLM provider
    )
    _bootstrap.print_result(approved)

    if not approved.allowed:
        print("Unexpected: expected an ALLOW for the customer's own order.")
        raise SystemExit(1)

    # Build the answer **only** from the approved, already-transformed
    # values — never from any raw data source.
    details = approved.granted_values()
    summary = approved.llm_response or (
        f"Order {details.get('order_id')}: {details.get('status')}."
    )
    _respond_to_user(approved, summary)

    # ── 3. The audit trail explains both decisions ───────────────────
    # Anyone can see their own audit events; compliance roles see more.
    # (Requires a credential with audit access — this is best-effort.)
    print("=" * 72)
    print("Audit trail for this session (own events):")
    try:
        page = client.audit_events(session_id="demo-end-to-end-1", limit=10)
        for event in page.items:
            print(
                f"  {event.timestamp}  {event.action:<17} "
                f"{event.overall_decision or '-':<16} "
                f"reasons={','.join(event.reason_codes) or '-'}"
            )
    except _bootstrap.ContextShieldError as exc:
        print(f"  (audit query not available for this identity: {exc})")
    print("=" * 72)


def _respond_to_user(result, text: str) -> None:
    """The only place user-visible answers are produced."""
    print(f"\n  agent says: {text}")
    print(f"  (grounded in: {result.overall_decision})")


if __name__ == "__main__":
    sys.exit(_bootstrap.run_safely(main))
